import { writeFileSync } from "node:fs";
import { oklchToCss, themeTokens, THEMES } from "../src/lib/theme-tokens.ts";

const block = (selector: string, theme: (typeof THEMES)[number], mode: "light" | "dark") => {
  const lines = Object.entries(themeTokens(theme, mode)).map(
    ([name, value]) => `  --${name}: ${oklchToCss(value)};`,
  );
  return `${selector} {\n${lines.join("\n")}\n}`;
};

const css = THEMES.flatMap((theme) => [
  block(`:root[data-theme="${theme.id}"]`, theme, "light"),
  block(`:root[data-theme="${theme.id}"].dark`, theme, "dark"),
]).join("\n\n");

writeFileSync(
  "src/styles/themes.css",
  `/* Generated by scripts/generate-themes.ts. Edit src/lib/theme-tokens.ts instead. */\n\n${css}\n`,
);
